import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { parseEnv } from 'node:util';
import { fileURLToPath } from 'node:url';

// Hosting-provider environment variables take precedence over the ignored local .env.
const projectRoot = new URL('../', import.meta.url);
const envFile = fileURLToPath(new URL('.env', projectRoot));
if (existsSync(envFile)) {
  const local = parseEnv(readFileSync(envFile, 'utf8').replace(/^\uFEFF/, ''));
  for (const [name, value] of Object.entries(local)) {
    if (process.env[name] === undefined) process.env[name] = value;
  }
}

const env = process.env;
const required = [
  'FIREBASE_API_KEY', 'FIREBASE_AUTH_DOMAIN', 'FIREBASE_PROJECT_ID',
  'FIREBASE_DATABASE_URL', 'FIREBASE_APP_ID',
];
const configured = required.filter(name => env[name]?.trim());
if (configured.length && configured.length !== required.length) {
  throw new Error(`Incomplete Firebase configuration. Missing: ${required.filter(name => !env[name]?.trim()).join(', ')}`);
}

const config = {
  siteUrl: env.APP_SITE_URL,
  ...(configured.length ? {
    firebase: {
      apiKey: env.FIREBASE_API_KEY,
      authDomain: env.FIREBASE_AUTH_DOMAIN,
      projectId: env.FIREBASE_PROJECT_ID,
      databaseURL: env.FIREBASE_DATABASE_URL,
      appId: env.FIREBASE_APP_ID,
      messagingSenderId: env.FIREBASE_MESSAGING_SENDER_ID,
    },
  } : {}),
};

writeFileSync(new URL('public/runtime-config.js', projectRoot),
  `// Generated by npm run config. Public browser configuration only.\nwindow.__ALLY_APP_CONFIG__ = ${JSON.stringify(config, null, 2)};\n`);
console.log(`Runtime configuration generated (${configured.length ? 'Firebase configured' : 'local mode'}).`);
